import { describe, expect, it } from "vitest";
import { formatThaiBahtText } from "@/features/shared/thai-baht-text";

describe("Thai baht wording", () => {
  it.each([
    [232200, "สองแสนสามหมื่นสองพันสองร้อยบาทถ้วน"],
    [0, "ศูนย์บาทถ้วน"],
    [1, "หนึ่งบาทถ้วน"],
    [11, "สิบเอ็ดบาทถ้วน"],
    [21, "ยี่สิบเอ็ดบาทถ้วน"],
    [101, "หนึ่งร้อยเอ็ดบาทถ้วน"],
    [1000000, "หนึ่งล้านบาทถ้วน"],
    [1000001, "หนึ่งล้านเอ็ดบาทถ้วน"],
    [1000000000000, "หนึ่งล้านล้านบาทถ้วน"],
    [0.01, "ศูนย์บาทหนึ่งสตางค์"],
    [0.21, "ศูนย์บาทยี่สิบเอ็ดสตางค์"],
    [232200.5, "สองแสนสามหมื่นสองพันสองร้อยบาทห้าสิบสตางค์"],
    [1.005, "หนึ่งบาทหนึ่งสตางค์"],
    [9.999, "สิบบาทถ้วน"],
    [-21.25, "ลบยี่สิบเอ็ดบาทยี่สิบห้าสตางค์"],
    [-0.001, "ศูนย์บาทถ้วน"],
    [NaN, "-"],
    [Infinity, "-"],
  ])("formats %s as %s", (amount, expected) => {
    expect(formatThaiBahtText(amount)).toBe(expected);
  });
});
